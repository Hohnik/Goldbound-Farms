import assert from 'node:assert/strict';
import {earningsFor,hasGph,hasValue,formatEarning} from './public/earnings.js';
const entry=metrics=>earningsFor({kind:'farm',metrics});
const fish=entry({reported_gold_per_hour:7400,reset_hypothetical_gold_per_hour:19000});
assert.equal(formatEarning(fish[0]),'7,400g/h');
assert.equal(fish[0].kind,'recorded');
assert.equal(hasValue(fish),true);
const raid=entry({expected_gold_per_lockout_hour:9200,active_time_extrapolated_gold_per_hour:25000});
assert.equal(formatEarning(raid[0]),'≈9,200g/h');
assert.match(raid[0].basis,/reset cap/);
const pet=entry({minutes_approx:180,Dark_Whelpling:1,quoted_pet_gold:58500});
assert.equal(formatEarning(pet[0]),'58,500g');
assert.equal(hasGph(pet),false);
assert.equal(hasValue(pet),true);
assert.deepEqual(entry({boxes:100,quoted_daily_region_sales:12,token_gold:296000,cash_gold:246000}),[]);
assert.deepEqual(entry({minutes_lower_bound:60,appraisal_gold_approx:63045,digits_uncertain:true}),[]);
const basket=entry({minutes:60,raw_appraisal_gold:2839,processed_appraisal_gold:4600,processing_time_included:false});
assert.equal(formatEarning(basket[0]),'≈2,839g/h');
assert.deepEqual(entry({raw_appraisal_gold:2120,margin_gold:1077}),[]);
assert.deepEqual(entry({theoretical_gold_per_hour:426000,misleading_appraiser_gold_per_hour:3000}),[]);
const range=entry({reported_gold_per_hour_range:[14000,18000]});
assert.equal(formatEarning(range[0]),'14,000–18,000g/h');
assert.equal(formatEarning(entry({quoted_market_gold_lower_bound:500000})[0]),'≥500,000g');
assert.equal(earningsFor({kind:'observation',metrics:{cash_gold:71665,derived_overall_gold_per_played_hour:1405.2}}).length,0);
assert.equal(formatEarning(entry({quoted_EU_gold:83000,quoted_NA_gold:3000})[0]),'83,000g');
assert.equal(formatEarning(entry({reported_gold_per_hour:.03})[0]),'0.03g/h');
assert.equal(formatEarning(entry({quoted_market_gold:140000,quoted_sale_gold:14000})[0]),'14,000g');
assert.equal(entry({output_market_gold:4459})[0].kind,'batch');
const {readFile}=await import('node:fs/promises');
const rows=JSON.parse(await readFile(new URL('./public/audit-data.json',import.meta.url),'utf8')).records;
const byId=new Map(rows.map(r=>[r.id,r]));
const rotation=earningsFor(byId.get('E032-19'),byId);
assert.equal(hasValue(rotation),true);
assert.equal(hasGph(rotation),false);
assert.equal(formatEarning(rotation.find(b=>b.item==='Twilights Blade'&&b.kind==='item')),'>3,000,000g');
assert.equal(formatEarning(rotation.find(b=>b.item==='Twilights Blade'&&b.kind==='sale')),'>350,000g');
assert.equal(formatEarning(rotation.find(b=>b.item==='Krol the Decapitator'&&b.kind==='sale')),'<200,000g');
assert.equal(rotation.find(b=>b.item==='Pattern: High Society Top Hat').obtained,false);
assert.equal(rotation.find(b=>b.item==='Reins of Poseidus').obtained,true);
assert.equal(rotation.find(b=>b.kind==='component'&&b.sourceRecordId==='E032-15').min,4400);
assert.ok(rotation.every(b=>b.source_refs.length>0));
const badges=id=>earningsFor(byId.get(id),byId);
const hybrid=badges('E033-22');
assert.equal(formatEarning(hybrid.find(b=>b.label==='Trade goods')),'≈6,600g/h');
assert.equal(formatEarning(hybrid.find(b=>b.label==='Lucky sample')),'9,000g/h');
assert.equal(hybrid.find(b=>b.item==='Darting Hatchling').obtained,true);
const scimitar=badges('E036-14');
assert.equal(formatEarning(scimitar[0]),'>230,000g');
assert.equal(scimitar[0].obtained,true);
assert.equal(hasGph(scimitar),false);
assert.equal(hasValue(scimitar),true);
const uldaman=badges('E034-03');
assert.equal(formatEarning(uldaman.find(b=>b.item==='Digmaster 5000')),'8,000,000g');
assert.equal(uldaman.find(b=>b.item==='Digmaster 5000').label,'Listing');
assert.equal(uldaman.find(b=>b.item==='Papal Fez').obtained,false);
assert.equal(hasGph(uldaman),false);
assert.equal(formatEarning(badges('E005-11')[0]),'≈20g/day');
assert.equal(formatEarning(badges('E020-14')[0]),'250–500g/use');
assert.equal(hasGph(badges('E020-14')),false);
assert.equal(formatEarning(badges('E028-21').find(b=>b.negative)),'−4,500g');
assert.equal(formatEarning(badges('E014-07')[0]),'583g/h');
assert.equal(formatEarning(badges('E026-06')[0]),'≈2,991.43g/h');
assert.equal(formatEarning(badges('E027-14')[0]),'30,000g');
assert.equal(hasValue(badges('E027-14')),true);
assert.equal(hasGph(badges('E027-14')),false);
assert.equal(hasGph(badges('E036-17')),false);
assert.ok(badges('E036-17').some(b=>b.kind==='component'));
assert.equal(formatEarning(badges('E014-19').find(b=>b.item==='Wedding Ring')),'Quoted up to 400,000g');
assert.deepEqual(badges('E032-02'),[]); // uncorroborated quest gold held out
assert.deepEqual(badges('E038-23'),[]); // health and item levels are not gold
const secondary=entry({Cloak_of_Night_quoted_gold:270000,Blackvenom_Blade_quoted_gold:170000});
assert.ok(secondary.some(b=>b.item==='Blackvenom Blade'&&b.min===170000));
for(const r of rows)for(const b of earningsFor(r,byId)){
 assert.ok(b.source_refs.length>0,`${r.id} lacks value evidence`);
 assert.ok(Number.isFinite(b.min)&&Number.isFinite(b.max));
 assert.ok(!formatEarning(b).includes('undefined'));
}
console.log('Earnings checks passed: rates, rare targets, receipts, component separation, per-use units, losses, and uncertain/excluded figures.');
